#!/usr/bin/env python3
"""Generate crates/core/src/frameforge/nvidia/driver_settings.rs from NVIDIA's
NvApiDriverSettings.h (MIT, https://github.com/NVIDIA/nvapi)."""
import re, sys
src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
names = dict(re.findall(r'#define\s+(\w+)_STRING\s+L"([^"]*)"', src))
ids = re.search(r"enum ESetting \{(.*?)\};", src, re.S).group(1)
settings = []
for m in re.finditer(r"(\w+)_ID\s*=\s*(0x[0-9A-Fa-f]+)", ids):
    settings.append((m.group(1), int(m.group(2), 16)))
values = {}
for m in re.finditer(r"enum EValues_(\w+) \{(.*?)\};", src, re.S):
    key, body = m.group(1), m.group(2)
    consts, default = [], None
    table = {}
    for line in body.split("\n"):
        line = line.split("//")[0].strip().rstrip(",")
        if not line or "=" not in line:
            continue
        name, val = [x.strip() for x in line.split("=", 1)]
        short = name[len(key) + 1:] if name.startswith(key + "_") else name
        if short == "NUM_VALUES":
            continue
        if short == "DEFAULT":
            default = table.get(val)
            if default is None:
                try: default = int(val, 0)
                except ValueError: default = None
            continue
        try:
            num = int(val, 0)
        except ValueError:
            num = table.get(val)
            if num is None:
                continue
        num &= 0xFFFFFFFF
        table[name] = num
        consts.append((short, num))
    values[key] = (consts, default)
out = ['//! Generated by tools/frameforge/gen_nv_settings.py from `NvApiDriverSettings.h` in NVIDIA\'s',
       '//! NVAPI SDK (<https://github.com/NVIDIA/nvapi>, MIT licence, Copyright (c)',
       '//! NVIDIA Corporation). Do not edit by hand.',
       '//!',
       '//! These are the settings NVIDIA documents: id, constant name, display name,',
       '//! and the named values of each DWORD setting.', '',
       'pub struct OfficialSetting {', '    pub id: u32,', '    pub constant: &\'static str,', '    pub name: &\'static str,',
       '    pub default: Option<u32>,', '    pub values: &\'static [(&\'static str, u32)],', '}', '',
       '#[rustfmt::skip]', 'pub static SETTINGS: &[OfficialSetting] = &[']
for key, sid in settings:
    consts, default = values.get(key, ([], None))
    vals = ", ".join(f'("{n}", 0x{v:08X})' for n, v in consts)
    d = f"Some(0x{default & 0xFFFFFFFF:08X})" if default is not None else "None"
    name = names.get(key, "").replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'    OfficialSetting {{ id: 0x{sid:08X}, constant: "{key}", name: "{name}", default: {d}, values: &[{vals}] }},')
out.append('];')
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(len(settings), "settings,", sum(len(v[0]) for v in values.values()), "values")
